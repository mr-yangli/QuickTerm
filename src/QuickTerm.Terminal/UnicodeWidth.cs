    /// <summary>Columns the codepoint occupies: 0 for combining marks, 2 for wide, 1 for everything else.</summary>
    public static int Of(int rune)
    {
        if ((uint)rune < 0x20 || rune == 0x7F)
            return 0;
        if (rune < 0x300)
            return 1;
        if (InRanges(Combining, rune))
            return 0;
        return InRanges(Wide, rune) ? 2 : 1;
    }

    private static bool InRanges((int Start, int End)[] ranges, int rune)
    {
        var lo = 0;
        var hi = ranges.Length - 1;
        while (lo <= hi)
        {
            var mid = (lo + hi) / 2;
            var (start, end) = ranges[mid];
            if (rune < start)
                hi = mid - 1;
            else if (rune > end)
                lo = mid + 1;
            else
                return true;
        }
        return false;
    }
